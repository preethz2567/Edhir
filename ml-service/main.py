import os
import threading
import time

import pika
import psycopg2
import psycopg2.extras
from fastapi import FastAPI

# ── Config from environment (falls back to docker-compose defaults) ────────────
DB_HOST = os.getenv("DB_HOST", "postgres")
DB_PORT = int(os.getenv("DB_PORT", "5432"))
DB_NAME = os.getenv("DB_NAME", "edhir")
DB_USER = os.getenv("DB_USER", "user")
DB_PASS = os.getenv("DB_PASS", "password")

RABBIT_HOST = os.getenv("RABBIT_HOST", "rabbitmq")
RABBIT_PORT = int(os.getenv("RABBIT_PORT", "5672"))
QUEUE_NAME = "request.metadata"

VELOCITY_WINDOW_SECS = 60
VELOCITY_MAX = 20  # requests in window that maps to score 100

app = FastAPI()


# ── FastAPI health endpoints (kept from Week 1) ────────────────────────────────

@app.get("/score")
def score_get():
    return {"status": "ML Service is up", "note": "Week 3 placeholder"}


