"""
Edhir ML Service — Week 3 placeholder implementation.

This file has two responsibilities:
  1. FastAPI HTTP endpoint (GET /score, POST /score) — kept from Week 1 for
     circuit-breaker health checks.
  2. RabbitMQ consumer thread — receives RequestMetadata JSON messages from
     the proxy-service, computes a simple velocity-based anomaly score, and
     writes it back to sessions.current_score in Postgres.

Week 3 scoring logic (PLACEHOLDER — will be replaced in Week 4):
  - Count how many requests came from the same session_id in the last 60 s.
  - Map linearly: 0 requests → 0, ≥20 requests → 100.
  - This is purely request-velocity; no Isolation Forest model is used yet.
  - See comment block at bottom of compute_score() for Week 4 design notes.
"""

