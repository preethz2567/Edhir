# ── Postgres helper ────────────────────────────────────────────────────────────

def get_db_conn():
    return psycopg2.connect(
        host=DB_HOST, port=DB_PORT, dbname=DB_NAME,
        user=DB_USER, password=DB_PASS
    )


# ── Week 3 placeholder scoring ─────────────────────────────────────────────────

def compute_score(session_id: str, conn) -> float:
    """
    WEEK 3 PLACEHOLDER — simple request-velocity score.

    Counts the number of requests in the requests table for this session_id
    in the last VELOCITY_WINDOW_SECS seconds and scales linearly to 0-100.

    ──────────────────────────────────────────────────────────────────────────
    WEEK 4 PLAN (Isolation Forest model):
      - Replace this function with a call to a trained IsolationForest that
        operates on a feature vector: [velocity, path_entropy, method_mix,
        ua_consistency, time_of_day_bin].
      - The model will be loaded once at startup from a serialised .pkl file
        generated by the training pipeline in ml-service/train.py.
      - Score will be the model's decision_function() output mapped to 0-100.
    ──────────────────────────────────────────────────────────────────────────
    """
    with conn.cursor() as cur:
        cur.execute(
            """
            SELECT COUNT(*) FROM requests
            WHERE session_id = %s::uuid
              AND timestamp >= NOW() - INTERVAL '%s seconds'
            """,
            (session_id, VELOCITY_WINDOW_SECS)
        )
        count = cur.fetchone()[0]

    raw_score = min(count / VELOCITY_MAX, 1.0) * 100.0
    return round(raw_score, 2)


def update_session_score(session_id: str, score: float, conn) -> None:
    with conn.cursor() as cur:
        cur.execute(
            "UPDATE sessions SET current_score = %s WHERE id = %s::uuid",
            (score, session_id)
        )
    conn.commit()


# ── RabbitMQ consumer (runs in a background thread) ───────────────────────────

# In-memory store for tracking delivery attempts of transient failures
# Maps delivery_tag to attempt count
retry_cache = {}

def on_message(ch, method, properties, body):
    try:
        try:
            data = json.loads(body)
        except json.JSONDecodeError as e:
            print(f"[ml-service] Malformed JSON, routing to DLQ: {e}")
            ch.basic_nack(delivery_tag=method.delivery_tag, requeue=False)
            return

        session_id = data.get("sessionId")
        if not session_id:
            print("[ml-service] Missing sessionId, routing to DLQ")
            ch.basic_nack(delivery_tag=method.delivery_tag, requeue=False)
            return

        conn = get_db_conn()
        try:
            score = compute_score(str(session_id), conn)
            update_session_score(str(session_id), score, conn)
            
            # Success
            ch.basic_ack(delivery_tag=method.delivery_tag)
            retry_cache.pop(method.delivery_tag, None)
            
        finally:
            conn.close()

    except psycopg2.Error as e:
        # Transient DB error, we should retry up to 3 times
        attempts = retry_cache.get(method.delivery_tag, 0) + 1
        if attempts >= 3:
            print(f"[ml-service] DB error, max retries reached, routing to DLQ: {e}")
            ch.basic_nack(delivery_tag=method.delivery_tag, requeue=False)
            retry_cache.pop(method.delivery_tag, None)
        else:
            print(f"[ml-service] DB error, transient retry {attempts}/3: {e}")
            retry_cache[method.delivery_tag] = attempts
            ch.basic_nack(delivery_tag=method.delivery_tag, requeue=True)
            
    except Exception as e:
        # Non-recoverable error
        print(f"[ml-service] Non-recoverable error, routing to DLQ: {e}")
        ch.basic_nack(delivery_tag=method.delivery_tag, requeue=False)
        retry_cache.pop(method.delivery_tag, None)


def start_consumer():
    """Retry-loop: wait for RabbitMQ to be ready, then start consuming."""
    while True:
        try:
            connection = pika.BlockingConnection(
                pika.ConnectionParameters(host=RABBIT_HOST, port=RABBIT_PORT)
            )
            channel = connection.channel()
            channel.queue_declare(
                queue=QUEUE_NAME, 
                durable=True,
                arguments={
                    'x-dead-letter-exchange': 'request.metadata.dlx',
                    'x-dead-letter-routing-key': 'request.metadata.dlq'
                }
            )
            channel.basic_qos(prefetch_count=1)
            channel.basic_consume(queue=QUEUE_NAME, on_message_callback=on_message)
            print(f"[ml-service] Consumer started on queue '{QUEUE_NAME}'")
            channel.start_consuming()
        except pika.exceptions.AMQPConnectionError as e:
            print(f"[ml-service] RabbitMQ connection error, retrying in 5s: {e}")
            time.sleep(5)
        except Exception as e:
            print(f"[ml-service] Unexpected consumer error, retrying in 5s: {e}")
            time.sleep(5)


# Start the consumer in a daemon thread so FastAPI startup is not blocked
consumer_thread = threading.Thread(target=start_consumer, daemon=True)
consumer_thread.start()
